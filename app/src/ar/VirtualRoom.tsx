import {
  ViroAmbientLight,
  ViroBox,
  ViroNode,
  ViroOmniLight,
  ViroQuad,
  ViroSphere,
  ViroText,
} from '@reactvision/react-viro';

import {
  DOOR_OUTER_HALF_WIDTH,
  DOOR_OUTER_HEIGHT,
  LIGHT_MASK_ROOM,
  ROOM,
} from './doorGeometry';

const HALF_W = ROOM.width / 2;
const MID_Y = ROOM.height / 2;
const MID_Z = ROOM.frontZ - ROOM.depth / 2;
const BACK_Z = ROOM.frontZ - ROOM.depth;

// The front wall has a hole for the doorway. The hole is 3 cm smaller than the outer
// size of the frame, so the frame always covers its edge.
const HOLE_HALF_W = DOOR_OUTER_HALF_WIDTH - 0.03;
const HOLE_TOP = DOOR_OUTER_HEIGHT - 0.03;
const SIDE_W = HALF_W - HOLE_HALF_W;

/**
 * The "VR" side: a closed, obviously artificial room behind the doorway.
 *
 * Local frame: origin on the floor in the middle of the threshold, +Y up, the room
 * extends towards -Z (see `doorGeometry.ts`). Everything is built from ViroReact
 * primitives and textures generated by `scripts/generate-assets.mjs`.
 *
 * The room has its own lights (bit mask LIGHT_MASK_ROOM) that do not touch AR objects.
 */
export function VirtualRoom() {
  return (
    <ViroNode>
      {/* ---- own lighting ---- */}
      <ViroAmbientLight color="#8fa0ff" intensity={260} influenceBitMask={LIGHT_MASK_ROOM} />
      <ViroOmniLight
        color="#fff1d0"
        intensity={1100}
        position={[0, ROOM.height - 0.3, MID_Z]}
        attenuationStartDistance={2}
        attenuationEndDistance={9}
        influenceBitMask={LIGHT_MASK_ROOM}
      />

      {/* ---- shell: floor, ceiling, four walls ---- */}
      <ViroQuad
        position={[0, 0, MID_Z]}
        rotation={[-90, 0, 0]}
        width={ROOM.width}
        height={ROOM.depth}
        materials={['roomFloor']}
      />
      <ViroQuad
        position={[0, ROOM.height, MID_Z]}
        rotation={[90, 0, 0]}
        width={ROOM.width}
        height={ROOM.depth}
        materials={['roomCeiling']}
      />
      <ViroQuad
        position={[0, MID_Y, BACK_Z]}
        width={ROOM.width}
        height={ROOM.height}
        materials={['roomWall']}
      />
      <ViroQuad
        position={[-HALF_W, MID_Y, MID_Z]}
        rotation={[0, 90, 0]}
        width={ROOM.depth}
        height={ROOM.height}
        materials={['roomWall']}
      />
      <ViroQuad
        position={[HALF_W, MID_Y, MID_Z]}
        rotation={[0, -90, 0]}
        width={ROOM.depth}
        height={ROOM.height}
        materials={['roomWall']}
      />
      {/* Front wall = three pieces around the doorway (left, right, above). */}
      <ViroQuad
        position={[-(HOLE_HALF_W + SIDE_W / 2), MID_Y, ROOM.frontZ]}
        rotation={[0, 180, 0]}
        width={SIDE_W}
        height={ROOM.height}
        materials={['roomFrontWall']}
      />
      <ViroQuad
        position={[HOLE_HALF_W + SIDE_W / 2, MID_Y, ROOM.frontZ]}
        rotation={[0, 180, 0]}
        width={SIDE_W}
        height={ROOM.height}
        materials={['roomFrontWall']}
      />
      <ViroQuad
        position={[0, (HOLE_TOP + ROOM.height) / 2, ROOM.frontZ]}
        rotation={[0, 180, 0]}
        width={HOLE_HALF_W * 2}
        height={ROOM.height - HOLE_TOP}
        materials={['roomFrontWall']}
      />

      {/* ---- a few objects ---- */}
      <ViroBox
        position={[0, 0.4, -3]}
        width={0.5}
        height={0.8}
        length={0.5}
        materials={['roomPedestal']}
        lightReceivingBitMask={LIGHT_MASK_ROOM}
      />
      <ViroBox
        position={[0, 1.15, -3]}
        rotation={[35, 0, 35]}
        width={0.35}
        height={0.35}
        length={0.35}
        materials={['roomCube']}
        lightReceivingBitMask={LIGHT_MASK_ROOM}
        animation={{ name: 'roomSpin', run: true, loop: true }}
      />
      <ViroSphere
        position={[-1.2, 0.35, -2.2]}
        radius={0.35}
        materials={['roomSphere']}
        lightReceivingBitMask={LIGHT_MASK_ROOM}
      />
      <ViroBox
        position={[1.25, 0.3, -3.8]}
        rotation={[0, 25, 0]}
        width={0.6}
        height={0.6}
        length={0.6}
        materials={['roomCrate']}
        lightReceivingBitMask={LIGHT_MASK_ROOM}
      />

      {/* ---- labels ---- */}
      <ViroText
        text="VIRTUAL ROOM"
        position={[0, 2.0, BACK_Z + 0.05]}
        width={3.5}
        height={0.8}
        style={{ fontSize: 40, fontWeight: '700', color: '#40e8f0', textAlign: 'center', textAlignVertical: 'center' }}
      />
      {/* Above the doorway on the inside, so the way back is obvious after turning around. */}
      <ViroText
        text="EXIT TO AR"
        position={[0, (HOLE_TOP + ROOM.height) / 2, ROOM.frontZ - 0.03]}
        rotation={[0, 180, 0]}
        width={1.6}
        height={0.5}
        style={{ fontSize: 20, fontWeight: '700', color: '#ffffff', textAlign: 'center', textAlignVertical: 'center' }}
      />
    </ViroNode>
  );
}
