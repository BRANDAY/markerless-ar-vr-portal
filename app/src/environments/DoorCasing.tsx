import { Viro3DObject, ViroAnimations, ViroMaterials, ViroNode } from '@reactvision/react-viro';
import { useEffect, useState } from 'react';

/**
 * A wooden door casing for the portal that fits a doorway of any size, and an optional plank door.
 *
 * The casing is built from parts that are stretched only along their own length, so the moulding
 * keeps its cross-section whatever the doorway measures:
 *
 *   two side casings   1 m long models, scaled in Y to the height of the opening
 *   head casing        1 m long model, scaled in X to the width of the opening
 *   two mitred corners never scaled
 *   threshold bar      1 m long model, scaled in X
 *   "window"           transparent 1 x 1 m tunnel, scaled in X and Y; the inner world is visible
 *                      only through it (the portal renderer shows the inner scene where the frame
 *                      has geometry whose texture alpha is <= 0.1)
 *
 * All materials are unlit (`Constant`): the shading of the moulding is painted into the texture, so
 * no lights and no light bit masks are needed. Models and textures are generated by
 * `assets/environments/door_casing/build/build_door.py`; the numbers below repeat that script.
 */
export const DOOR_CASING = {
  /** Width of the casing face, outwards from the edge of the opening. */
  casingWidth: 0.085,
  /** How far the casing stands out of the wall on the real side (+Z). */
  front: 0.018,
  /** The jamb lining: its thickness and how far it reaches into the inner world (-Z). */
  liningThickness: 0.022,
  liningDepth: 0.06,
  thresholdHeight: 0.012,
  /** Model size of the door leaf (width, height, thickness); it is scaled to the doorway. */
  leafModel: [0.83, 2.01, 0.042],
  /** Triangles: casing with the window / door leaf. */
  casingTriangles: 240,
  leafTriangles: 1226,
} as const;

/** The transparent tunnel is this much larger than the opening, so its walls hide inside the lining. */
const WINDOW_MARGIN = 0.008;
/** The leaf overlaps the lining on the hinge side, the lock side and the top; gap above the floor. */
const LEAF_LAP = 0.015;
const LEAF_FLOOR_GAP = 0.006;
/** Gap between the end of the lining and the closed leaf. */
const LEAF_CLEARANCE = 0.004;

const MODELS = {
  postLeft: require('../../assets/environments/door_casing/casing_post_left.obj'),
  postRight: require('../../assets/environments/door_casing/casing_post_right.obj'),
  cornerLeft: require('../../assets/environments/door_casing/casing_corner_left.obj'),
  cornerRight: require('../../assets/environments/door_casing/casing_corner_right.obj'),
  head: require('../../assets/environments/door_casing/casing_head.obj'),
  threshold: require('../../assets/environments/door_casing/casing_threshold.obj'),
  window: require('../../assets/environments/door_casing/portal_window.obj'),
  leaf: require('../../assets/environments/door_casing/door_leaf.obj'),
};

const CASING_TEXTURE = require('../../assets/environments/door_casing/door_casing.jpg');
const LEAF_TEXTURE = require('../../assets/environments/door_casing/door_leaf.jpg');

// Registered once, when this module is first imported. `cullMode: 'None'` because the portal renderer
// needs the frame to be visible from both sides (it also switches culling off itself).
ViroMaterials.createMaterials({
  envDoorCasing: { lightingModel: 'Constant', diffuseTexture: CASING_TEXTURE, cullMode: 'None' },
  envDoorLeaf: { lightingModel: 'Constant', diffuseTexture: LEAF_TEXTURE, cullMode: 'None' },
  // Every texel is fully transparent, so filtering and mip levels cannot bring any alpha in.
  envPortalWindow: {
    lightingModel: 'Constant',
    diffuseTexture: require('../../assets/environments/door_casing/portal_window.png'),
    minificationFilter: 'Nearest',
    magnificationFilter: 'Nearest',
    mipFilter: 'Nearest',
  },
});

const registered = new Set<string>();

/** Name of the casing or leaf material, optionally multiplied by a colour (it can only darken). */
function woodMaterial(kind: 'Casing' | 'Leaf', tint?: string): string {
  const base = `envDoor${kind}`;
  if (!tint) {
    return base;
  }
  const name = `${base}_${tint.replace(/[^0-9a-zA-Z]/g, '')}`;
  if (!registered.has(name)) {
    ViroMaterials.createMaterials({
      [name]: {
        lightingModel: 'Constant',
        diffuseTexture: kind === 'Casing' ? CASING_TEXTURE : LEAF_TEXTURE,
        diffuseColor: tint,
        cullMode: 'None',
      },
    });
    registered.add(name);
  }
  return name;
}

/** Distance from the floor to the portal origin (the centre of the opening) for a doorway of this height. */
export function doorCasingOriginHeight(height: number): number {
  return height / 2;
}

export interface DoorCasingProps {
  /** Clear width of the real doorway, metres. */
  width: number;
  /** Clear height of the real doorway, floor to the underside of the head, metres. */
  height: number;
  /** Low wooden bar on the floor that hides the seam between the real and the virtual floor. Default true. */
  threshold?: boolean;
  /**
   * Colour multiplied into the wood, e.g. '#c8c8c8' to make the casing 20 % darker in a dim room.
   * Not set = the texture as it is (the brightest the casing can be).
   */
  tint?: string;
  onLoadEnd?: () => void;
  onError?: (message: string) => void;
}

/**
 * The casing and the transparent window. Put it DIRECTLY inside `<ViroPortal>`: it renders a list of
 * `Viro3DObject`s and nothing else, because the Android bridge accepts no other child type there.
 *
 * Local frame = the frame of the `ViroPortalScene`: origin in the CENTRE of the opening (the portal
 * renderer needs that), +Y up, +Z towards the real side. The floor is at y = -height / 2.
 *
 *   <ViroPortalScene passable position={...}>           // origin: centre of the opening
 *     <ViroPortal>
 *       <DoorCasing width={w} height={h} />
 *     </ViroPortal>
 *     <ViroSkyBox color="#070716" />
 *     <ViroNode position={[0, -doorCasingOriginHeight(h), 0]}>   // floor-level frame
 *       <SponzaAtrium />
 *       <DoorLeaf width={w} height={h} />
 *     </ViroNode>
 *   </ViroPortalScene>
 */
export function DoorCasing({ width, height, threshold = true, tint, onLoadEnd, onError }: DoorCasingProps) {
  const hw = width / 2;
  const hh = height / 2;
  const wood = [woodMaterial('Casing', tint)];
  const fail = (event: { nativeEvent?: unknown } | undefined) =>
    onError?.(JSON.stringify(event?.nativeEvent ?? {}));

  return (
    <>
      <Viro3DObject source={MODELS.postLeft} type="OBJ" materials={wood} position={[-hw, -hh, 0]} scale={[1, height, 1]} onError={fail} />
      <Viro3DObject source={MODELS.postRight} type="OBJ" materials={wood} position={[hw, -hh, 0]} scale={[1, height, 1]} onError={fail} />
      <Viro3DObject source={MODELS.cornerLeft} type="OBJ" materials={wood} position={[-hw, hh, 0]} onError={fail} />
      <Viro3DObject source={MODELS.cornerRight} type="OBJ" materials={wood} position={[hw, hh, 0]} onError={fail} />
      <Viro3DObject source={MODELS.head} type="OBJ" materials={wood} position={[0, hh, 0]} scale={[width, 1, 1]} onError={fail} />
      {threshold ? (
        <Viro3DObject source={MODELS.threshold} type="OBJ" materials={wood} position={[0, -hh, 0]} scale={[width, 1, 1]} onError={fail} />
      ) : null}
      {/* Last on purpose: the transparent window is drawn after the wood. Its bottom edge is exactly on the floor. */}
      <Viro3DObject
        source={MODELS.window}
        type="OBJ"
        materials={['envPortalWindow']}
        position={[0, WINDOW_MARGIN / 2, 0]}
        scale={[width + 2 * WINDOW_MARGIN, height + WINDOW_MARGIN, 1]}
        onLoadEnd={onLoadEnd}
        onError={fail}
      />
    </>
  );
}

export interface DoorLeafProps {
  /** Clear width and height of the doorway, the same numbers as for `DoorCasing`. */
  width: number;
  height: number;
  /** Which side the hinges are on, as seen from the real side. Default 'right'. */
  hinge?: 'left' | 'right';
  /** Open or closed. Default true (open). A closed leaf hides the inner world behind the door. */
  open?: boolean;
  /** How far the open leaf swings into the inner world, degrees. Default 100. */
  openAngle?: number;
  /** Swing smoothly when `open` changes. Default true; set false if the animation misbehaves on a device. */
  animated?: boolean;
  /** Duration of the swing, milliseconds. Default 1600. */
  durationMs?: number;
  /** Colour multiplied into the leaf, see `DoorCasingProps.tint`. */
  tint?: string;
  onClick?: () => void;
  onError?: (message: string) => void;
}

function swingAnimation(angle: number, durationMs: number): string {
  const name = `envDoorSwing_${angle < 0 ? 'm' : 'p'}${Math.round(Math.abs(angle) * 10)}_${Math.round(durationMs)}`;
  if (!registered.has(name)) {
    ViroAnimations.registerAnimations({
      [name]: { properties: { rotateY: angle }, duration: durationMs, easing: 'EaseInEaseOut' },
    });
    registered.add(name);
  }
  return name;
}

/**
 * A plank door with strap hinges that swings into the inner world. It belongs to the INNER WORLD
 * (a sibling of the environment, not a child of `ViroPortal`), so from the real side it is seen only
 * through the doorway.
 *
 * Local frame = the frame of the environment: origin on the floor in the middle of the threshold,
 * +Y up, the inner world towards -Z. The closed leaf lies just behind the end of the jamb lining and
 * overlaps it by 1.5 cm on three sides, like a door hung on the face of the wall.
 */
export function DoorLeaf({
  width,
  height,
  hinge = 'right',
  open = true,
  openAngle = 100,
  animated = true,
  durationMs = 1600,
  tint,
  onClick,
  onError,
}: DoorLeafProps) {
  const [modelWidth, modelHeight, modelThickness] = DOOR_CASING.leafModel;
  const side = hinge === 'right' ? 1 : -1;
  // Rotation about +Y that swings the free edge towards -Z: negative for hinges on the right.
  const target = open ? -side * openAngle : 0;

  // `rest` is the angle the `rotation` prop carries. While an animation runs the prop keeps the old
  // angle (the animation moves the node natively); when it finishes the prop takes the new angle.
  const [rest, setRest] = useState(target);
  useEffect(() => {
    if (!animated) {
      setRest(target);
    }
  }, [animated, target]);
  const swinging = animated && rest !== target;

  const hingeX = side * (width / 2 + LEAF_LAP);
  const hingeZ = -(DOOR_CASING.liningDepth + LEAF_CLEARANCE + modelThickness / 2);

  return (
    <ViroNode
      position={[hingeX, LEAF_FLOOR_GAP, hingeZ]}
      rotation={[0, animated ? rest : target, 0]}
      animation={
        swinging
          ? { name: swingAnimation(target, durationMs), run: true, loop: false, onFinish: () => setRest(target) }
          : undefined
      }
    >
      <Viro3DObject
        source={MODELS.leaf}
        type="OBJ"
        materials={[woodMaterial('Leaf', tint)]}
        // The model has its hinges on the right (it extends to -X); turned around for hinges on the left.
        rotation={[0, hinge === 'right' ? 0 : 180, 0]}
        scale={[(width + 2 * LEAF_LAP) / modelWidth, (height + LEAF_LAP - LEAF_FLOOR_GAP) / modelHeight, 1]}
        onClick={onClick}
        onError={(event) => onError?.(JSON.stringify(event?.nativeEvent ?? {}))}
      />
    </ViroNode>
  );
}
